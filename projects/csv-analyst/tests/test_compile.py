def _norm(value: Any) -> Any:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return None
    if isinstance(value, pd.Timestamp):
        return (
            value.strftime("%Y-%m-%d %H:%M")
            if value.hour or value.minute
            else value.date().isoformat()
        )
    if isinstance(value, float):
        return round(value, 4)
    if hasattr(value, "item"):  # numpy scalars
        return _norm(value.item())
    return value


def _pandas_rows(code: str, df: pd.DataFrame) -> list[tuple[Any, ...]]:
    body = code.split("\n", 3)[3]  # drop "import pandas", blank line and "df = ..."
    scope: dict[str, Any] = {"pd": pd, "df": df.copy()}
    exec(body, scope)  # noqa: S102 - code generated by our own compiler in a test
    result = scope["result"]
    if isinstance(result, dict):
        return [tuple(_norm(v) for v in result.values())]
    return [tuple(_norm(v) for v in row) for row in result.itertuples(index=False)]


def _sql_value(value: Any) -> Any:
    if isinstance(value, str) and len(value) == 10 and value[4] == "-" and value[7] == "-":
        return value
    return _norm(value)


@pytest.mark.parametrize("plan", PLANS, ids=range(len(PLANS)))
def test_sql_and_pandas_agree(
    plan: QueryPlan, schema: DatasetSchema, csv_settings: CsvSettings, frame: pd.DataFrame
) -> None:
    checked = validate_plan(plan, schema)
    assert checked.ok and checked.plan is not None, checked.issues
    compiled = compile_plan(checked.plan, schema)
    result = run_query(
        csv_settings.bundled_db, compiled.sql, compiled.params, csv_settings, max_rows=100
    )
    assert not result.truncated
    sql_rows = sorted((tuple(_sql_value(v) for v in r) for r in result.rows), key=repr)
    pandas_rows = sorted(_pandas_rows(compiled.pandas, frame), key=repr)
    assert sql_rows == pandas_rows


def test_sorting_and_limit(schema: DatasetSchema, csv_settings: CsvSettings) -> None:
    plan = validate_plan(p([m("sum", "revenue")], ["country"], sort=D, limit=3), schema).plan
    assert plan is not None
    compiled = compile_plan(plan, schema)
    result = run_query(
        csv_settings.bundled_db, compiled.sql, compiled.params, csv_settings, max_rows=3
    )
    values = [r[1] for r in result.rows]
    assert len(values) == 3
    assert values == sorted(values, reverse=True)
    assert result.rows[0][0] == "United Kingdom"


def test_values_are_bound_never_inlined(schema: DatasetSchema) -> None:
    hostile = "x'); DROP TABLE sales; --"
    plan = QueryPlan(metrics=[m("count")], filters=[f("description", "contains", hostile)], limit=5)
    checked = validate_plan(plan, schema)
    assert checked.plan is not None
    compiled = compile_plan(checked.plan, schema)
    assert hostile not in compiled.sql
    assert "DROP" not in compiled.sql
    assert compiled.params[0] == f"%{hostile}%"
    assert compiled.sql.count("?") == len(compiled.params)


def test_like_wildcards_in_search_text_are_literal(
    schema: DatasetSchema, csv_settings: CsvSettings
) -> None:
    for text, expected_zero in [("%", True), ("_", True), ("HEART", False)]:
        plan = validate_plan(
            p([m("count")], filters=[f("description", "contains", text)]), schema
        ).plan
        assert plan is not None
        compiled = compile_plan(plan, schema)
        result = run_query(
            csv_settings.bundled_db, compiled.sql, compiled.params, csv_settings, max_rows=1
        )
        assert (result.rows[0][0] == 0) is expected_zero, text


def test_identifiers_are_quoted() -> None:
    assert quote_ident("revenue") == '"revenue"'
    assert quote_ident('we"ird') == '"we""ird"'


def test_time_bucket_sql(schema: DatasetSchema) -> None:
    plan = QueryPlan(
        metrics=[m("sum", "revenue")],
        time_bucket=TimeBucket(column="invoiced_at", grain="month"),
        sort="group_asc",
    )
    compiled = compile_plan(plan, schema)
    assert "date_trunc('month', \"invoiced_at\")" in compiled.sql
    assert compiled.chart == "line"


def test_every_development_plan_compiles_to_one_statement(schema: DatasetSchema) -> None:
    for case in CASES:
        if case.expected is None:
            continue
        checked = validate_plan(case.expected, schema)
        assert checked.plan is not None
        compiled = compile_plan(checked.plan, schema)
        assert compiled.sql.lstrip().startswith("SELECT")
        assert ";" not in compiled.sql
        assert compiled.summary


def test_column_labels(schema: DatasetSchema) -> None:
    plan = QueryPlan(
        metrics=[m("sum", "revenue"), m("count_distinct", "customer_id"), m("count")],
        time_bucket=TimeBucket(column="invoiced_at", grain="month"),
    )
    compiled = compile_plan(plan, schema)
    assert [c.label for c in compiled.columns] == [
        "Month",
        "Total revenue",
        "Number of distinct customers",
        "Number of invoice lines",
    ]


def test_suggested_charts_must_fit_the_result(schema: DatasetSchema) -> None:
    grouped = p([m("sum", "revenue")], ["country"])
    assert compile_plan(grouped.model_copy(update={"chart": "line"}), schema).chart == "bar"
    assert compile_plan(grouped.model_copy(update={"chart": "table"}), schema).chart == "table"
    single = p([m("sum", "revenue")])
    assert compile_plan(single.model_copy(update={"chart": "bar"}), schema).chart == "number"


def test_time_bucket_name_does_not_clash_with_a_column(upload_settings: CsvSettings) -> None:
    from reluai_csv.datasets import UploadStore

    upload = UploadStore(upload_settings).save(
        b"month,day,sales\nJan,2024-01-05,3\nFeb,2024-02-07,4\n", "m.csv"
    )
    schema = upload.schema()
    plan = QueryPlan(
        metrics=[m("sum", "sales")],
        group_by=["month"],
        time_bucket=TimeBucket(column="day", grain="month"),
    )
    checked = validate_plan(plan, schema)
    assert checked.plan is not None, checked.issues
    compiled = compile_plan(checked.plan, schema)
    names = [c.name for c in compiled.columns]
    assert len(names) == len(set(names))
    result = run_query(upload.path, compiled.sql, compiled.params, upload_settings, max_rows=10)
    assert len(result.rows) == 2
